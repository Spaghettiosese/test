// Writes docs/FEATURES.md from the features every module declares (src/core/registry.js FEATURES).
import { writeFileSync } from 'node:fs';
await import('../src/content/index.js');
const { FEATURES } = await import('../src/core/registry.js');
const byCat = {};
for (const f of FEATURES) (byCat[f.cat] ||= []).push(f.text);
const cats = Object.keys(byCat).sort((a, b) => byCat[b].length - byCat[a].length);
let md = `# Misa's Little Life: feature list\n\nGenerated by \`node tools/features.mjs\` from the features each module declares next to the code that implements it.\n\n**${FEATURES.length} features** in ${cats.length} categories.\n\n`;
md += cats.map((c) => `- [${c}](#${c.toLowerCase().replace(/[^a-z0-9]+/g, '-')}) (${byCat[c].length})`).join('\n') + '\n\n';
let n = 0;
for (const c of cats) { md += `## ${c}\n\n`; for (const t of byCat[c]) md += `${++n}. ${t}\n`; md += '\n'; }
writeFileSync(new URL('../docs/FEATURES.md', import.meta.url), md);
console.log(`${FEATURES.length} features in ${cats.length} categories -> docs/FEATURES.md`);
